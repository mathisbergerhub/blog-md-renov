const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const OUTPUT = path.join(ROOT, "api", "_listing-manifest.js");
const FILES = [
  "index.html",
  "aides-subventions.html",
  "fenetres-vitrages.html",
  "isolation-thermique.html",
  "volets-stores.html",
  "portes-portails.html",
  "tous-les-articles-exterieur.html",
];

const pages = Object.fromEntries(
  FILES
    .filter((file) => fs.existsSync(path.join(ROOT, file)))
    .map((file) => [file, fs.readFileSync(path.join(ROOT, file), "utf8")]),
);

const output = `// Generated by scripts/build-listing-manifest.js. Do not edit by hand.
module.exports = ${JSON.stringify(pages, null, 2)};
`;

fs.writeFileSync(OUTPUT, output, "utf8");
console.log(`Manifeste listings genere : ${Object.keys(pages).length} page(s).`);
