const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const OUTPUT = path.join(ROOT, "api", "_article-manifest.js");

function listMarkdownFiles() {
  const rootFiles = fs
    .readdirSync(ROOT)
    .filter((file) => file.endsWith(".html.md"))
    .map((file) => path.join(ROOT, file));

  const contentDir = path.join(ROOT, "content", "articles");
  const contentFiles = fs.existsSync(contentDir)
    ? fs
        .readdirSync(contentDir)
        .filter((file) => file.endsWith(".md"))
        .map((file) => path.join(contentDir, file))
    : [];

  return [...rootFiles, ...contentFiles];
}

function toPortablePath(filePath) {
  return path.relative(ROOT, filePath).replace(/\\/g, "/");
}

const articles = listMarkdownFiles()
  .map((filePath) => ({
    filePath: toPortablePath(filePath),
    markdown: fs.readFileSync(filePath, "utf8"),
  }))
  .sort((a, b) => a.filePath.localeCompare(b.filePath, "fr"));

const output = `// Generated by scripts/build-article-manifest.js. Do not edit by hand.
module.exports = ${JSON.stringify(articles, null, 2)};
`;

fs.writeFileSync(OUTPUT, output, "utf8");
console.log(`Manifeste articles genere : ${articles.length} article(s).`);
